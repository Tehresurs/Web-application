import os
import unittest

import psycopg
import test_references
from test_daily_control import http_request
from app.database.migrate_luvr_directories import apply_migration
from app.repositories import employees


@unittest.skipUnless(os.getenv("DAILY_CONTROL_TEST_DB") == "1", "Requires isolated PostgreSQL tests")
class LuvrDirectoryTests(unittest.TestCase):
    def setUp(self):
        test_references.ReferenceDatabaseTests.setUp(self)
        self.conn.execute("""ALTER TABLE positions ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 3);
            ALTER TABLE employees ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 3);
            ALTER TABLE positions ADD COLUMN created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP;
            ALTER TABLE positions ADD COLUMN updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP;
            ALTER TABLE employees ADD COLUMN created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP;
            ALTER TABLE employees ADD COLUMN updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP;
            INSERT INTO positions(id,name,action_description) VALUES(1,'Старая должность','Действия');""")

    def position(self, location="OFFICE", schedule="SHIFT", **extra):
        status, body = http_request("POST", "/api/positions", {
            "name": f"Должность {location} {schedule}", "action_description":"Описание",
            "specialty":"ОС/СТ", "work_location":location,"work_schedule":schedule, **extra,
        })
        self.assertEqual(status,200,body)
        return body["item"]

    def test_three_allowed_combinations_and_specialty(self):
        for location,schedule in (("OFFICE","FIVE_TWO"),("OFFICE","SHIFT"),("OBJECT","SHIFT")):
            with self.subTest(location=location,schedule=schedule):
                item=self.position(location,schedule)
                self.assertEqual((item["specialty"],item["work_location"],item["work_schedule"]),("ОС/СТ",location,schedule))
                self.assertEqual(item["action_description"],"Описание")
        self.assertEqual(len(http_request("GET","/api/positions")[1]["items"]),4)

    def test_object_five_two_and_missing_schedule_rejected(self):
        for schedule in ("FIVE_TWO",None):
            status,body=http_request("POST","/api/positions",{"name":"Запрещено","work_location":"OBJECT","work_schedule":schedule})
            self.assertEqual(status,400)
            self.assertIn("Вахта",body["message"])
        self.assertEqual(self.conn.execute("SELECT count(*) FROM positions").fetchone()[0],1)

    def test_patch_validates_merged_state_and_preserves_omitted_settings(self):
        item=self.position("OFFICE","FIVE_TWO")
        route=f'/api/positions/{item["id"]}'
        self.assertEqual(http_request("PATCH",route,{"name":"Изменённая","work_location":"OBJECT"})[0],400)
        updated=http_request("PATCH",route,{"name":"Изменённая","action_description":"Новые действия"})[1]["item"]
        self.assertEqual(updated["specialty"],"ОС/СТ")
        self.assertEqual(updated["work_schedule"],"FIVE_TWO")
        updated=http_request("PATCH",route,{"name":"Полевая","work_location":"OBJECT","work_schedule":"SHIFT"})[1]["item"]
        self.assertEqual(updated["work_location"],"OBJECT")
        self.assertEqual(http_request("PATCH",route,{"name":"Полевая","work_schedule":None})[0],400)

    def test_invalid_enums_rejected(self):
        for fields in ({"work_location":"REMOTE"},{"work_schedule":"DAILY"}):
            self.assertEqual(http_request("POST","/api/positions",{"name":"Новая",**fields})[0],422)

    def test_employee_personal_settings_create_and_patch(self):
        item=self.position("OBJECT","SHIFT")
        body={"full_name":"Новый Сотрудник","position_id":item["id"],"nrs_number":"00-А / любой формат", "max_shift_days":45,"max_off_shift_days":21}
        status,result=http_request("POST","/api/employees",body)
        self.assertEqual(status,200,result)
        employee_id=result["id"]
        employee=next(x for x in employees.get_employees() if x["id"]==employee_id)
        for key in ("nrs_number","max_shift_days","max_off_shift_days"):
            self.assertEqual(employee[key],body[key])
        self.assertEqual(employee["specialty"],"ОС/СТ")
        # Old clients do not erase newly configured personal settings.
        route=f'/api/employees/{employee_id}'
        self.assertEqual(http_request("PATCH",route,{"full_name":"Новое ФИО","position_id":item["id"]})[0],200)
        employee=next(x for x in employees.get_employees() if x["id"]==employee_id)
        self.assertEqual(employee["max_shift_days"],45)
        self.assertEqual(http_request("PATCH",route,{"full_name":"Новое ФИО","nrs_number":None,"max_shift_days":None,"max_off_shift_days":None})[0],200)
        row=self.conn.execute("SELECT nrs_number,max_shift_days,max_off_shift_days FROM employees WHERE id=%s",(employee_id,)).fetchone()
        self.assertEqual(row,(None,None,None))

    def test_employee_position_change_derives_metadata_without_duplication(self):
        field=self.position("OBJECT","SHIFT")
        office=self.position("OFFICE","FIVE_TWO",specialty="Офисная")
        for position in (field,office):
            status,_=http_request("PATCH","/api/employees/1",{"full_name":"Сотрудник","position_id":position["id"]})
            self.assertEqual(status,200)
            item=next(x for x in employees.get_employees() if x["id"]==1)
            self.assertEqual(item["specialty"],position["specialty"])
            self.assertEqual(item["work_schedule"],position["work_schedule"])
        columns=[r[0] for r in self.conn.execute("SELECT attname FROM pg_attribute WHERE attrelid='employees'::regclass AND attnum>0 AND NOT attisdropped").fetchall()]
        self.assertTrue(set(("specialty","work_location","work_schedule")).isdisjoint(columns))
        employees.rename_position(office["id"],office["name"],specialty="Новое сокращение")
        self.assertEqual(next(x for x in employees.get_employees() if x["id"]==1)["specialty"],"Новое сокращение")

    def test_personal_limits_must_be_positive_integers(self):
        for key in ("max_shift_days","max_off_shift_days"):
            for value in (0,-1,1.5,True,"30",2147483648):
                with self.subTest(key=key,value=value):
                    for method,route in (("POST","/api/employees"),("PATCH","/api/employees/1")):
                        self.assertEqual(http_request(method,route,{"full_name":"Сотрудник",key:value})[0],422)
        with self.assertRaises(ValueError): employees.update_employee(1,"Сотрудник",max_shift_days=-1)

    def test_legacy_nulls_and_unchanged_old_fields(self):
        position=employees.get_positions()[0]
        self.assertEqual(position["action_description"],"Действия")
        for key in ("specialty","work_location","work_schedule"): self.assertIsNone(position[key])
        employee=employees.get_employees()[0]
        for key in ("nrs_number","max_shift_days","max_off_shift_days","specialty","work_location","work_schedule"): self.assertIsNone(employee[key])

    def test_database_checks(self):
        for location,schedule in (("OBJECT","FIVE_TWO"),("OBJECT",None),("BAD","SHIFT"),("OFFICE","BAD")):
            with self.assertRaises(psycopg.errors.CheckViolation), self.conn.transaction():
                self.conn.execute("UPDATE positions SET work_location=%s,work_schedule=%s WHERE id=1",(location,schedule))
        for column in ("max_shift_days","max_off_shift_days"):
            for value in (0,-1):
                with self.assertRaises(psycopg.errors.CheckViolation), self.conn.transaction():
                    self.conn.execute(f"UPDATE employees SET {column}=%s WHERE id=1",(value,))

    def test_migration_preserves_every_old_value_and_repeats(self):
        columns={"positions":["specialty","work_location","work_schedule"],"employees":["nrs_number","max_shift_days","max_off_shift_days"]}
        for table,names in columns.items():
            for name in names:self.conn.execute(f"ALTER TABLE {table} DROP COLUMN {name} CASCADE")
        tables=("positions","employees","employee_assignments","daily_control_results","construction_objects","construction_subobjects","po_types","object_categories","value_aliases")
        before={t:self.conn.execute(f"SELECT to_jsonb(r) FROM {t} r ORDER BY id").fetchall() for t in tables}
        apply_migration(self.conn);apply_migration(self.conn)
        for table in tables:
            suffix="".join("-'"+name+"'" for name in columns.get(table,[]))
            after=self.conn.execute(f"SELECT to_jsonb(r){suffix} FROM {table} r ORDER BY id").fetchall()
            self.assertEqual(before[table],after,table)

    def test_openapi_new_fields(self):
        status,schema=http_request("GET","/openapi.json")
        self.assertEqual(status,200)
        for model,fields in (("PositionRequest",("specialty","work_location","work_schedule")),("EmployeeRequest",("nrs_number","max_shift_days","max_off_shift_days"))):
            self.assertTrue(set(fields)<=schema["components"]["schemas"][model]["properties"].keys())
